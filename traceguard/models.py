"""
Data models and structure definitions for TraceGuard SIEM.
Zero external dependencies; uses Python standard library dataclasses.
"""

from dataclasses import dataclass, field, asdict
from typing import List, Dict, Optional, Any
from datetime import datetime, timezone


@dataclass
class LogEvent:
    """Represents a normalized security event parsed from raw logs."""
    timestamp: datetime
    log_type: str                  # auth, web, syslog, windows, json
    source_ip: str = "unknown"
    user: str = "unknown"
    action: str = "unknown"        # failed_login, success_login, sudo_exec, web_request, port_scan
    status: str = "unknown"        # success, failure, error
    raw_message: str = ""
    details: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["timestamp"] = self.timestamp.isoformat()
        return d


@dataclass
class IncidentPlaybook:
    """NIST SP 800-61 incident response playbook actions (Certiport Domain 5.4)."""
    detection_summary: str
    containment_actions: List[str]
    containment_command: str        # e.g., iptables / netsh block command
    eradication_steps: List[str]
    recovery_steps: List[str]
    compliance_impact: str          # GDPR, PCI-DSS, HIPAA reporting triggers

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class SecurityAlert:
    """Security alert generated by detection engine matching MITRE ATT&CK TTPs."""
    alert_id: str
    title: str
    severity: str                  # CRITICAL, HIGH, MEDIUM, LOW
    timestamp: str
    source_ip: str
    target_user: str
    event_count: int
    mitre_tactic: str              # e.g. Credential Access, Discovery, Initial Access
    mitre_technique_id: str        # e.g. T1110 (Brute Force), T1046 (Network Discovery)
    mitre_technique_name: str
    description: str
    evidence_samples: List[str] = field(default_factory=list)
    playbook: Optional[IncidentPlaybook] = None

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        return d


@dataclass
class SiemReport:
    """Consolidated SIEM audit & threat hunting report."""
    session_title: str
    run_timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"))
    total_logs_processed: int = 0
    duration_seconds: float = 0.0
    alerts: List[SecurityAlert] = field(default_factory=list)
    source_ips_seen: int = 0
    top_threat_actors: List[Dict[str, Any]] = field(default_factory=list)
    mitre_breakdown: Dict[str, int] = field(default_factory=dict)
    severity_breakdown: Dict[str, int] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)
